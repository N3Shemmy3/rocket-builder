export const AUTOFIT_SURPLUS = ['capsule', 'tank', 'engine'];

export function getInstalledPartByGroup(installedSet, slotGroup) {
  for (const key of installedSet) {
    if (PARTS[key]?.slotGroup === slotGroup) {
      return { key, part: PARTS[key] };
    }
  }
  return null;
}

export function installPartInSet(installedSet, partKey) {
  const next = new Set(installedSet);
  const target = PARTS[partKey];
  if (!target) return next;

  for (const existingKey of [...next]) {
    const existing = PARTS[existingKey];
    if (!existing) {
      next.delete(existingKey);
      continue;
    }
    if (existing.slotGroup === target.slotGroup) {
      next.delete(existingKey);
      continue;
    }
    if (
      target.slotGroup === 'upperSolid' &&
      (existing.slotGroup === 'upperTank' || existing.slotGroup === 'upperEngine')
    ) {
      next.delete(existingKey);
      continue;
    }
    if (
      (target.slotGroup === 'upperTank' || target.slotGroup === 'upperEngine') &&
      existing.slotGroup === 'upperSolid'
    ) {
      next.delete(existingKey);
    }
  }

  next.add(partKey);
  return next;
}
